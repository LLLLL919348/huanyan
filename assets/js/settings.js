  function compile(list, flags) {
    const out = [];
    (list || []).forEach(function (item) {
      if (!item || !item.re) return;
      try { out.push({ re: new RegExp(item.re, flags || ''), label: item.label || '' }); }
      catch (e) { console.warn('忽略非法正则：' + item.re); }
    });
    return out;
  }

