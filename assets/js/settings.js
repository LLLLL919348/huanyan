  function clone(o) { return JSON.parse(JSON.stringify(o)); }
  function deepMerge(base, over) {
    if (!over || typeof over !== 'object') return base;
    Object.keys(over).forEach(function (k) {
      const v = over[k];
      if (Array.isArray(v)) base[k] = v;
      else if (v && typeof v === 'object') base[k] = deepMerge(base[k] && typeof base[k] === 'object' ? base[k] : {}, v);
      else if (v !== undefined && v !== null && v !== '') base[k] = v;
    });
    return base;
  }

  async function load() {
    try {
      const res = await fetch('/api/settings', { cache: 'no-store' });
      if (!res.ok) throw new Error('HTTP ' + res.status);
      const data = await res.json();
      if (data && data.ok && data.settings) {
        cur = deepMerge(clone(DEFAULTS), data.settings);
        loaded = true;
      }
    } catch (e) {
      /* 没有后端（file:// 或静态服务）时静默使用内置默认值 */
      loaded = false;
    }
    return cur;
  }

