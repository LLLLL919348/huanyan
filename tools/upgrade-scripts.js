/* ==========================================================================
   剧本升级：信息账本 + 会误导的角色 + 叙事与引导约束

   解决的问题（来自真实试玩反馈）：
     1. 玩家缺信息，角色却向玩家索要玩家不可能知道的东西
        —— 典型例子：闻鹤年开局就问「你要找的人叫什么名字」，可剧本从没告诉玩家妹妹叫什么。
     2. 推进度低、引导差：角色答完已知情节就不往下带，玩家只能反复问 NPC。
     3. 叙事感弱：环境与情节描写少，角色态度前后不一。

   做法（分两层，避免规则又变"太杂"）：
     · 通用层写进 globalPrompt（只写一次，所有本子共用）：
       提问的规矩、每次回复的叙事密度、结尾必须给可执行方向、卡住时主动出手、
       角色可以有私心并说谎 —— 但谎必须自洽且留下破绽。
     · 剧本层写进每个 resource.prompt 的【玩家已知】【双方共知】【只有你知道】
       【你的私心与误导】【态度基准】：每个本子的具体人名、秘密、谎话与破绽都不同，
       这些不能通用，必须逐个写。
     · 玩家侧：plotReminder 开头几条改成"你已知"，让开局卡就把基础信息交到玩家手里；
       openingHints 改成玩家照着就能说出口的句子（不含"说出名字"这种踩雷选项）。

   幂等：已经带【玩家已知】的本子会跳过，重复执行不会叠加。
   用法： node tools/upgrade-scripts.js            （改 data/resources.json 与 assets/js/resources.js）
         node tools/upgrade-scripts.js --dry-run  （只打印差异，不落盘）
   ========================================================================== */
