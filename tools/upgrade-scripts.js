/* ============================== 拼装 ============================== */
function promptBlock(s) {
  const L = [];
  L.push('【玩家已知（他确实知道的，别再当秘密，也别向他要他没有的东西）】');
  s.knows.forEach(function (x) { L.push('· ' + x); });
  L.push('【双方共知（可以当话头用，不必解释）】');
  s.shared.forEach(function (x) { L.push('· ' + x); });
  L.push('【只有你知道的（分层揭示，不要一次说完）】');
  s.secret.forEach(function (x) { L.push('· ' + x); });
  L.push('【你的私心与误导】');
  s.agenda.forEach(function (x) { L.push(x); });
  L.push('【态度基准与转折】');
  s.attitude.forEach(function (x) { L.push(x); });
  return L.join('\n');
}

function insertBeforePromptEnd(prompt, block) {
  const MARK = '【输出格式】';
  const i = prompt.indexOf(MARK);
  if (i === -1) return prompt + '\n' + block;
  return prompt.slice(0, i) + block + '\n' + prompt.slice(i);
}

